-- -----------------------------------------------------------------------------
-- DOMÍNIOS: o domínio é mais que o tipo — inclui a regra de valores válidos.
-- -----------------------------------------------------------------------------
DO $$ BEGIN
    CREATE DOMAIN dm_nome AS varchar(120) CHECK (char_length(btrim(VALUE)) >= 2);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE DOMAIN dm_email AS varchar(120)
        CHECK (VALUE ~* '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    -- Código de negociação: PETR4, KNRI11, BOVA11, BTC...
    CREATE DOMAIN dm_ticker AS varchar(20) CHECK (VALUE ~ '^[A-Z0-9]{2,12}$');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    -- Preço unitário em reais; 8 casas para cripto e ativos de centavos
    CREATE DOMAIN dm_preco AS numeric(20, 8) CHECK (VALUE > 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    -- Quantidade negociada; cripto aceita frações de até 8 casas
    CREATE DOMAIN dm_quantidade AS numeric(24, 8) CHECK (VALUE > 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- -----------------------------------------------------------------------------
-- USUÁRIOS E CARTEIRAS
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuario (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    nome        dm_nome      NOT NULL,
    email       dm_email     NOT NULL,
    senha_hash  varchar(255) NOT NULL,
    perfil      varchar(10)  NOT NULL DEFAULT 'INVESTIDOR',
    ativo       boolean      NOT NULL DEFAULT true,
    criado_em   timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'INVESTIDOR'))
);

CREATE TABLE IF NOT EXISTS ativo (
    id             integer GENERATED BY DEFAULT AS IDENTITY,
    ticker         dm_ticker   NOT NULL,
    nome           varchar(120) NOT NULL,
    classe         varchar(10)  NOT NULL,
    simbolo_fonte  varchar(30)  NOT NULL,
    ativo          boolean      NOT NULL DEFAULT true,
    criado_em      timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_ativo PRIMARY KEY (id),
    CONSTRAINT uq_ativo_ticker UNIQUE (ticker),
    CONSTRAINT ck_ativo_classe CHECK (classe IN ('ACAO', 'FII', 'ETF', 'CRIPTO'))
);

CREATE TABLE IF NOT EXISTS carteira (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    usuario_id  integer     NOT NULL,
    nome        varchar(80) NOT NULL,
    descricao   text,
    criada_em   timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_carteira PRIMARY KEY (id),
    CONSTRAINT fk_carteira_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT uq_carteira_usuario_nome UNIQUE (usuario_id, nome)
);

CREATE TABLE IF NOT EXISTS operacao (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    carteira_id  integer        NOT NULL,
    ativo_id     integer        NOT NULL,
    tipo         varchar(6)     NOT NULL,
    data         date           NOT NULL,
    quantidade   dm_quantidade  NOT NULL,
    preco        dm_preco       NOT NULL,
    taxas        numeric(14, 2) NOT NULL DEFAULT 0,
    observacao   text,
    criado_em    timestamp(0)   NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_operacao PRIMARY KEY (id),
    CONSTRAINT fk_operacao_carteira FOREIGN KEY (carteira_id) REFERENCES carteira (id) ON DELETE CASCADE,
    CONSTRAINT fk_operacao_ativo FOREIGN KEY (ativo_id) REFERENCES ativo (id) ON DELETE RESTRICT,
    CONSTRAINT ck_operacao_tipo CHECK (tipo IN ('COMPRA', 'VENDA')),
    CONSTRAINT ck_operacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_operacao_preco CHECK (preco > 0),
    CONSTRAINT ck_operacao_taxas CHECK (taxas >= 0),
    CONSTRAINT ck_operacao_data CHECK (data >= DATE '1990-01-01')
);

CREATE INDEX IF NOT EXISTS ix_carteira_usuario_id ON carteira (usuario_id);
CREATE INDEX IF NOT EXISTS ix_operacao_carteira_id ON operacao (carteira_id);
CREATE INDEX IF NOT EXISTS ix_operacao_ativo_id ON operacao (ativo_id);
CREATE INDEX IF NOT EXISTS ix_operacao_carteira_data ON operacao (carteira_id, data);

-- -----------------------------------------------------------------------------
-- DADOS DE MERCADO (cache local das fontes externas)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cotacao (
    ativo_id    integer  NOT NULL,
    data        date     NOT NULL,
    fechamento  dm_preco NOT NULL,
    CONSTRAINT pk_cotacao PRIMARY KEY (ativo_id, data),
    CONSTRAINT fk_cotacao_ativo FOREIGN KEY (ativo_id) REFERENCES ativo (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS provento (
    ativo_id  integer  NOT NULL,
    data      date     NOT NULL,
    valor     dm_preco NOT NULL,
    CONSTRAINT pk_provento PRIMARY KEY (ativo_id, data),
    CONSTRAINT fk_provento_ativo FOREIGN KEY (ativo_id) REFERENCES ativo (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS taxa_cdi (
    data      date           NOT NULL,
    taxa_dia  numeric(12, 8) NOT NULL,
    CONSTRAINT pk_taxa_cdi PRIMARY KEY (data),
    CONSTRAINT ck_taxa_cdi_faixa CHECK (taxa_dia >= 0 AND taxa_dia < 1)
);

CREATE TABLE IF NOT EXISTS sincronizacao (
    chave          varchar(60)  NOT NULL,
    desde          date         NOT NULL,
    ate            date         NOT NULL,
    atualizado_em  timestamp    NOT NULL,
    fonte          varchar(20)  NOT NULL,
    CONSTRAINT pk_sincronizacao PRIMARY KEY (chave),
    CONSTRAINT ck_sincronizacao_periodo CHECK (ate >= desde)
);

-- -----------------------------------------------------------------------------
-- VALIDAÇÃO COM USUÁRIOS (laudos de teste)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS feedback_teste (
    id               integer GENERATED BY DEFAULT AS IDENTITY,
    nome_testador    dm_nome NOT NULL,
    email            dm_email,
    perfil_testador  varchar(80),
    data_teste       date     NOT NULL,
    funcionou        text     NOT NULL,
    nao_funcionou    text,
    nao_testado      text,
    sugestoes        text,
    nota             smallint NOT NULL,
    navegador        varchar(255),
    status           varchar(12) NOT NULL DEFAULT 'NOVO',
    tratativa        text,
    criado_em        timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_feedback_teste PRIMARY KEY (id),
    CONSTRAINT ck_feedback_nota CHECK (nota BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_status CHECK (status IN ('NOVO', 'EM_ANALISE', 'CORRIGIDO', 'DESCARTADO'))
);

CREATE TABLE IF NOT EXISTS feedback_anexo (
    id             integer GENERATED BY DEFAULT AS IDENTITY,
    feedback_id    integer      NOT NULL,
    nome_arquivo   varchar(255) NOT NULL,
    tipo_mime      varchar(50)  NOT NULL,
    tamanho_bytes  integer      NOT NULL,
    conteudo       bytea        NOT NULL,
    CONSTRAINT pk_feedback_anexo PRIMARY KEY (id),
    CONSTRAINT fk_anexo_feedback FOREIGN KEY (feedback_id) REFERENCES feedback_teste (id) ON DELETE CASCADE,
    CONSTRAINT ck_anexo_tamanho CHECK (tamanho_bytes BETWEEN 1 AND 2097152),
    CONSTRAINT ck_anexo_tipo CHECK (tipo_mime IN ('image/png', 'image/jpeg', 'image/webp', 'image/gif'))
);
CREATE INDEX IF NOT EXISTS ix_feedback_anexo_feedback_id ON feedback_anexo (feedback_id);

-- -----------------------------------------------------------------------------
-- VISÕES
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_operacoes_detalhadas AS
SELECT o.id, u.nome AS usuario, c.nome AS carteira, o.data, o.tipo, a.ticker, a.classe,
       o.quantidade, o.preco, o.taxas,
       CASE WHEN o.tipo = 'COMPRA' THEN o.quantidade * o.preco + o.taxas
            ELSE o.quantidade * o.preco - o.taxas END AS valor_total
  FROM operacao o
  JOIN carteira c ON c.id = o.carteira_id
  JOIN usuario  u ON u.id = c.usuario_id
  JOIN ativo    a ON a.id = o.ativo_id;

-- Quantidade em carteira hoje e valor pelo último fechamento conhecido
CREATE OR REPLACE VIEW vw_posicao_atual AS
SELECT c.id AS carteira_id, c.nome AS carteira, a.ticker, a.classe,
       sum(CASE WHEN o.tipo = 'COMPRA' THEN o.quantidade ELSE -o.quantidade END) AS quantidade,
       ult.data AS data_cotacao,
       ult.fechamento,
       sum(CASE WHEN o.tipo = 'COMPRA' THEN o.quantidade ELSE -o.quantidade END) * ult.fechamento AS valor
  FROM operacao o
  JOIN carteira c ON c.id = o.carteira_id
  JOIN ativo    a ON a.id = o.ativo_id
  LEFT JOIN LATERAL (
        SELECT q.data, q.fechamento FROM cotacao q
         WHERE q.ativo_id = a.id ORDER BY q.data DESC LIMIT 1
  ) ult ON true
 GROUP BY c.id, c.nome, a.ticker, a.classe, ult.data, ult.fechamento
HAVING sum(CASE WHEN o.tipo = 'COMPRA' THEN o.quantidade ELSE -o.quantidade END) > 0;

